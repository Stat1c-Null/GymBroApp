--changeset gymbro:002-settings
CREATE TABLE user_settings (
    user_id               BIGINT PRIMARY KEY,
    show_set_time         BOOLEAN NOT NULL DEFAULT FALSE,
    unit                  VARCHAR(8) NOT NULL DEFAULT 'lbs',
    distance_unit         VARCHAR(8) NOT NULL DEFAULT 'mi',
    goal_start_lbs        NUMERIC(6, 2),
    goal_start_date       DATE,
    goal_target_lbs       NUMERIC(6, 2),
    goal_target_date      DATE,
    entries_backfilled_at TIMESTAMP WITH TIME ZONE,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_settings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_settings_unit CHECK (unit IN ('kg', 'lbs')),
    CONSTRAINT ck_settings_distance_unit CHECK (distance_unit IN ('mi', 'km')),
    CONSTRAINT ck_settings_goal_pair CHECK (
        (goal_target_lbs IS NULL AND goal_target_date IS NULL)
        OR (goal_target_lbs IS NOT NULL AND goal_target_date IS NOT NULL)
    )
);
--rollback DROP TABLE user_settings;

