-- One row per (user, ISO week starting Monday) that has any logged activity.
--changeset gymbro:004-weeks
CREATE TABLE workout_weeks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    week_start DATE   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_weeks_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_weeks_user_start UNIQUE (user_id, week_start)
);
--rollback DROP TABLE workout_weeks;

-- A single logged exercise inside a week: either a strength exercise with
-- per-set rows, or one cardio session (mutually exclusive by muscle group).
-- exercise_name/muscle_group are denormalized on purpose: the log must survive
-- renaming or deleting the library entry, so exercise_id is nullable.
--changeset gymbro:004-entries
CREATE TABLE workout_entries (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_id               BIGINT       NOT NULL,
    day_of_week           SMALLINT     NOT NULL,
    exercise_id           BIGINT,
    exercise_name         VARCHAR(100) NOT NULL,
    muscle_group          VARCHAR(50)  NOT NULL,
    cardio_time_sec       INTEGER,
    cardio_distance_miles NUMERIC(8, 3),
    cardio_heart_rate     INTEGER,
    cardio_elevation_feet NUMERIC(8, 2),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_entries_week FOREIGN KEY (week_id) REFERENCES workout_weeks (id) ON DELETE CASCADE,
    CONSTRAINT fk_entries_exercise FOREIGN KEY (exercise_id) REFERENCES exercises (id) ON DELETE SET NULL,
    CONSTRAINT ck_entries_day CHECK (day_of_week BETWEEN 0 AND 6)
);
--rollback DROP TABLE workout_entries;

--changeset gymbro:004-entries-index
CREATE INDEX ix_entries_week ON workout_entries (week_id, day_of_week);
--rollback DROP INDEX ix_entries_week;

--changeset gymbro:004-entry-sets
CREATE TABLE entry_sets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id   BIGINT   NOT NULL,
    set_index  SMALLINT NOT NULL,
    reps       INTEGER,
    weight_lbs NUMERIC(6, 2),
    time_sec   INTEGER,
    CONSTRAINT fk_sets_entry FOREIGN KEY (entry_id) REFERENCES workout_entries (id) ON DELETE CASCADE,
    CONSTRAINT uq_sets_entry_index UNIQUE (entry_id, set_index)
);
--rollback DROP TABLE entry_sets;
