-- Body-weight log. Pounds are canonical, like every other weight in the app.
--changeset gymbro:005-body-weights
CREATE TABLE body_weights (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    weight_lbs NUMERIC(6, 2) NOT NULL,
    logged_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_weights_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_weights_positive CHECK (weight_lbs > 0)
);
--rollback DROP TABLE body_weights;

--changeset gymbro:005-body-weights-index
CREATE INDEX ix_weights_user_logged ON body_weights (user_id, logged_at DESC);
--rollback DROP INDEX ix_weights_user_logged;

-- The friend graph. One row per relationship, regardless of direction, so
-- accepting a request is a single UPDATE both sides see.
-- user_low_id/user_high_id are the same pair sorted ascending: they exist only
-- so the unordered pair can be UNIQUE without an expression index, which keeps
-- PostgreSQL and H2 behaving identically.
--changeset gymbro:005-friendships
CREATE TABLE friendships (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL,
    addressee_id BIGINT      NOT NULL,
    user_low_id  BIGINT      NOT NULL,
    user_high_id BIGINT      NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_addressee FOREIGN KEY (addressee_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_low FOREIGN KEY (user_low_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_high FOREIGN KEY (user_high_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_friendships_pair UNIQUE (user_low_id, user_high_id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('pending', 'accepted')),
    CONSTRAINT ck_friendships_self CHECK (requester_id <> addressee_id)
);
--rollback DROP TABLE friendships;

--changeset gymbro:005-friendships-index
CREATE INDEX ix_friendships_addressee ON friendships (addressee_id, status);
--rollback DROP INDEX ix_friendships_addressee;

--changeset gymbro:005-friendships-index-requester
CREATE INDEX ix_friendships_requester ON friendships (requester_id, status);
--rollback DROP INDEX ix_friendships_index_requester;
