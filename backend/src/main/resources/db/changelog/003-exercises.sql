-- The user's exercise library: what they train, not what they did.
-- Weight columns are pounds (the app's canonical lifted-weight unit).
--changeset gymbro:003-exercises
CREATE TABLE exercises (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    name            VARCHAR(100) NOT NULL,
    muscle_group    VARCHAR(50)  NOT NULL,
    usual_weight_lbs NUMERIC(6, 2),
    max_weight_lbs   NUMERIC(6, 2),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_exercises_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
--rollback DROP TABLE exercises;

--changeset gymbro:003-exercises-index
CREATE INDEX ix_exercises_user_group ON exercises (user_id, muscle_group);
